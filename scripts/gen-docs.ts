/**
 * Generates docs/COMPONENTS.md from the component registry, so the published
 * component list (and its verified / reported / approximated flags) can never
 * drift from the code.   Run:  npm run docs
 */
import { writeFileSync } from 'node:fs';
import * as THREE from 'three';
import { GeometryFactory } from '../src/core/GeometryFactory';
import { createModel } from '../src/data';
import { getMaterial } from '../src/data/materials';

const { registry, tree } = createModel();
const label = { verified: 'Apple spec', reported: 'Public teardown', approximated: 'Approximated' } as const;

let md = `# Component reference\n\n_Generated by \`npm run docs\` from \`src/data\`. Do not edit by hand._\n\n`;
md += `All sizes are the bounding box of the **procedural model** in millimetres – they are modelling approximations, not measurements of the real device.\n`;
md += `"Basis" describes what supports the part's *existence / construction*: Apple's published tech specs, a public third-party teardown, or neither (approximated).\n\n`;

const counts = { verified: 0, reported: 0, approximated: 0 };
let tris = 0;
let prims = 0;
for (const def of registry.all()) {
  counts[def.provenance]++;
  tris += GeometryFactory.triangleCount(def);
  prims += def.geometry.type === 'procedural' ? def.geometry.parts.length : 0;
}
md += `**${registry.size} components**, ${prims} primitives, ${tris.toLocaleString('en-US')} triangles — basis: ${counts.verified} Apple spec, ${counts.reported} public teardown, ${counts.approximated} approximated.\n\n`;

function section(nodeId: string, depth: number) {
  const node = tree.node(nodeId);
  md += `${'#'.repeat(Math.min(6, depth + 2))} ${node.name}\n\n`;
  const comps = tree.components(nodeId);
  if (comps.length) {
    md += `| ID | Component | Material | Model size (mm) | Explode offset (mm) | Basis | Note |\n|---|---|---|---|---|---|---|\n`;
    for (const id of comps) {
      const def = registry.get(id);
      const size = GeometryFactory.componentBox(def).getSize(new THREE.Vector3());
      const off = def.exploded.position.map((v, i) => +(v - def.assembled.position[i]).toFixed(2));
      md += `| \`${def.id}\` | ${def.name} | ${getMaterial(def.material).label} | ${size.x.toFixed(1)} × ${size.y.toFixed(1)} × ${size.z.toFixed(2)} | (${off.join(', ')}) | ${label[def.provenance]} | ${def.provenanceNote} |\n`;
    }
    md += '\n';
  }
  for (const child of tree.children(nodeId)) section(child.id, depth + 1);
}
section(tree.rootId, 0);

writeFileSync(new URL('../docs/COMPONENTS.md', import.meta.url), md);
console.log(`docs/COMPONENTS.md written (${registry.size} components, ${prims} primitives, ${tris} triangles; ${JSON.stringify(counts)})`);
